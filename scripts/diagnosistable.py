"""The RP-15 table: LLM diagnosis on the 20 labelled incidents, N runs each.

    python scripts/diagnosistable.py > docs/research/models/incident-diagnosis.md

Recomputed from `benchmark/results/diagnosis/<diagnoser>-run<k>.jsonl`. Per
diagnoser: RCA@1 per run, its mean and range, and a Wilson interval on the
pooled answers. The Phase 2 exit bar (top-1 ≥ 70% on 20 incidents) is shown
beside each row. The verdict itself is the owner's to write (RP-15).
"""

from __future__ import annotations

import json
import math
import re
import sys
from collections import defaultdict
from pathlib import Path

RECORDS = Path(__file__).resolve().parents[1] / "benchmark" / "results" / "diagnosis"
BAR = 0.70


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if not n:
        return (0.0, 0.0)
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return (max(0.0, centre - half), min(1.0, centre + half))


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    runs: dict[str, dict[int, list[dict]]] = defaultdict(dict)
    for path in sorted(RECORDS.glob("*-run*.jsonl")):
        m = re.fullmatch(r"(.+)-run(\d+)", path.stem)
        lines = [json.loads(x) for x in path.read_text(encoding="utf-8").splitlines() if x.strip()]
        if m and lines:
            runs[lines[0]["diagnoser"]][int(m.group(2))] = lines
    print("<!-- Generated by scripts/diagnosistable.py from benchmark/results/diagnosis/. Do not edit by hand. -->\n")
    print("# Diagnosis on the labelled incidents: general LLMs (RP-15)\n")
    print("The labelled incidents in `benchmark/incidents/`, with answer keys committed by the owner before any run "
          "(RP-13). Each diagnoser sees the incident's signals and the listed options, never the answer, and is "
          f"scored by the RP-14 harness. The Phase 2 exit bar is RCA@1 ≥ {BAR:.2f}.\n")
    print("| Diagnoser | Cases | Runs | RCA@1 per run | Mean RCA@1 | Pooled 95% CI | RCA@3 mean | Abstained | Errors | "
          "Meets the bar |")
    print("|---|---:|---:|---|---:|---:|---:|---:|---:|---|")
    if not runs:
        print("| — | 0 | 0 | — | — | — | — | — | — | no records yet |")
    for name, by_run in sorted(runs.items()):
        per = [sum(x["hit1"] for x in by_run[k]) / len(by_run[k]) for k in sorted(by_run)]
        rows = [x for k in sorted(by_run) for x in by_run[k]]
        hits = sum(x["hit1"] for x in rows)
        lo, hi = wilson(hits, len(rows))
        mean1 = sum(per) / len(per)
        mean3 = sum(x["hit3"] for x in rows) / len(rows)
        print(f"| {name} | {len(by_run[min(by_run)])} | {len(by_run)} | {', '.join(f'{v:.3f}' for v in per)} | "
              f"{mean1:.3f} | [{lo:.3f}, {hi:.3f}] | {mean3:.3f} | {sum(x['abstained'] for x in rows)} | "
              f"{sum(bool(x['error']) for x in rows)} | {'yes' if mean1 >= BAR else 'no'} |")
    print("\nAn error (provider timeout or invalid schema) counts as a miss and is listed on its own. LLMs run on CPU "
          "through Ollama on GitHub's runners, through the Gateway.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
