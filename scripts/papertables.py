"""Generate the paper's results tables from the run records.

    python scripts/papertables.py > docs/research/tables.md

Nothing here is typed by hand. A results table transcribed into prose drifts
from the data the moment either changes, and the drift is invisible — the number
in the paper still looks like a number. Tables are regenerated from
`benchmark/results/` and the paper includes them.

An arm with no records is printed as a row saying so, rather than left out. A
four-column comparison with two columns silently missing reads as a two-arm
study that always intended to be one.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, "packages/core")

from pashupatastra.metrics import (  # noqa: E402
    NOT_COMPUTABLE,
    compute,
    load_records,
    per_scenario,
)
from pashupatastra.significance import bootstrap_difference, holm, mcnemar  # noqa: E402

RESULTS = Path("benchmark/results")

# Every arm the paper claims to compare, whether or not it produced data.
ARMS = ("human", "runbook", "naive-llm", "pashupatastra")

ABSENT: dict[str, str] = {
    "human": (
        "not run — requires operators. A simulated human is the number this "
        "work would most like to see and the one nobody would check"
    ),
    "naive-llm": (
        "not run — requires a configured model. The deterministic stub would "
        "produce a second runbook under an LLM label"
    ),
}


def records_for(arm: str, suffix: str = "") -> list:
    path = RESULTS / arm / f"runs{suffix}.jsonl"
    return load_records(path) if path.exists() else []


LLM_ARMS = ("naive-llm", "pashupatastra-llm")


def llm_runs() -> dict[tuple[str, str], list]:
    """(arm, model) -> records, one file per model (adr/LLMBaselines)."""
    out: dict[tuple[str, str], list] = {}
    for arm in LLM_ARMS:
        folder = RESULTS / arm
        for path in sorted(folder.glob("runs-*.jsonl")) if folder.exists() else []:
            records = load_records(path)
            if records:
                out[(arm, records[0].model or path.stem.removeprefix("runs-"))] = records
    return out


def frr(records: list) -> float | None:
    m = compute(records)
    return m.frr if m.actions_executed else None


def by_scenario(records: list) -> dict[str, list]:
    grouped: dict[str, list] = {}
    for r in records:
        grouped.setdefault(r.scenario_id, []).append(r)
    return grouped


def compare(name_a: str, a: list, name_b: str, b: list) -> dict:
    keyed_b = {(r.scenario_id, r.run_index): r for r in b}
    pairs = [
        (ra.verdict == "correct", keyed_b[(ra.scenario_id, ra.run_index)].verdict == "correct")
        for ra in a
        if (ra.scenario_id, ra.run_index) in keyed_b
        and ra.verdict != "harness_error"
        and keyed_b[(ra.scenario_id, ra.run_index)].verdict != "harness_error"
    ]
    if not pairs:
        return {"name": f"{name_a} vs {name_b}", "p": None}
    test = mcnemar(pairs)
    ci = bootstrap_difference(by_scenario(a), by_scenario(b), frr)
    return {
        "name": f"{name_a} vs {name_b}",
        "counts": f"{test.only_a} / {test.only_b}",
        "p": test.p_value,
        "ci": f"[{ci[0]:+.3f}, {ci[1]:+.3f}]" if ci else "undefined (no actions)",
    }


def table5_rows(comparisons: list[dict]) -> list[str]:
    """Holm-adjusted across every comparison in the table (RP-10): a row
    survives only if it survives the whole family of tests."""
    tested = [c for c in comparisons if c["p"] is not None]
    for c, adjusted in zip(tested, holm([c["p"] for c in tested]), strict=True):
        c["adjusted"] = adjusted
    rows = []
    for c in comparisons:
        if c["p"] is None:
            rows.append(f"| {c['name']} | — | — | — | — | no paired runs |")
            continue
        verdict = "survives" if c["adjusted"] < 0.05 else "within chance"
        rows.append(f"| {c['name']} | {c['counts']} | {c['p']:.4f} | {c['adjusted']:.4f} | {c['ci']} | {verdict} |")
    return rows


def main() -> int:
    print("<!-- Generated by scripts/papertables.py. Do not edit by hand. -->\n")

    print("## Table 1 — Arms\n")
    print("Safety metric first. ARR is trivially maximised by acting recklessly,")
    print("so it is never printed above the rate of acting wrongly.\n")
    print("| Arm | FRR | HIR | ARR | VSR | Correct | n |")
    print("|-----|----:|----:|----:|----:|--------:|--:|")

    for arm in ARMS:
        records = records_for(arm)
        if not records:
            print(f"| {arm} | — | — | — | — | — | 0 |")
            continue
        m = compute(records)
        correct = round(m.correct / m.scoreable, 4) if m.scoreable else 0.0
        print(
            f"| {arm} | {m.frr:.4f} | {m.hir:.4f} | {m.arr:.4f} | "
            f"{m.vsr:.4f} | {correct:.4f} | {m.scoreable} |"
        )

    llm = llm_runs()
    for (arm, model), records in llm.items():
        m = compute(records)
        correct = round(m.correct / m.scoreable, 4) if m.scoreable else 0.0
        print(
            f"| {arm} · `{model}` | {m.frr:.4f} | {m.hir:.4f} | {m.arr:.4f} | "
            f"{m.vsr:.4f} | {correct:.4f} | {m.scoreable} |"
        )

    if llm:
        print("\n**LLM failures, counted apart from wrong answers** (adr/LLMBaselines):\n")
        print("| Arm · model | Provider or schema error | Off-list proposal | Model escalated |")
        print("|---|---:|---:|---:|")
        for (arm, model), records in llm.items():
            causes = [r.cause for r in records]
            print(
                f"| {arm} · `{model}` | {causes.count('llm_error')} | "
                f"{causes.count('off_list')} | {causes.count('model_escalated')} |"
            )

    print("\n**Arms with no data, and why:**\n")
    for arm, reason in ABSENT.items():
        if not records_for(arm) and not any(a == arm for a, _ in llm):
            print(f"- `{arm}` — {reason}")

    print("\n## Table 2 — Ablations\n")
    print("Only components the arm actually exercises can be ablated. Removing a")
    print("stage that never ran returns the baseline score and would be reported")
    print("as *no effect*, which reads as evidence the component does not matter.\n")
    print("| Variant | FRR | HIR | ARR | Correct | n |")
    print("|---------|----:|----:|----:|--------:|--:|")

    baseline = records_for("pashupatastra")
    if baseline:
        m = compute(baseline)
        correct = round(m.correct / m.scoreable, 4) if m.scoreable else 0.0
        print(f"| full architecture | {m.frr:.4f} | {m.hir:.4f} | {m.arr:.4f} "
              f"| {correct:.4f} | {m.scoreable} |")

    for ablation in ("no-policy", "no-verification"):
        records = records_for("pashupatastra", f"-{ablation}")
        if not records:
            print(f"| −{ablation} | — | — | — | — | 0 |")
            continue
        m = compute(records)
        correct = round(m.correct / m.scoreable, 4) if m.scoreable else 0.0
        print(f"| −{ablation} | {m.frr:.4f} | {m.hir:.4f} | {m.arr:.4f} "
              f"| {correct:.4f} | {m.scoreable} |")

    print("\n**Ablations that cannot be measured here:**\n")
    print("- `−hypothesis-evidence`, `−smriti`, `−adjacency` — all three sit in "
          "the reasoning path, which the benchmark arm never invokes")

    print("\n## Table 3 — Per-scenario results\n")
    print("Published rather than aggregated. A mean hides which cases fail, and")
    print("a scenario correct in some runs and not others is not a scenario that")
    print("works.\n")

    if baseline:
        print("| Scenario | Expected | Correct/runs | Verdicts |")
        print("|----------|----------|-------------:|----------|")
        for row in per_scenario(baseline):
            mark = " **UNSTABLE**" if row.unstable else ""
            verdicts = ", ".join(f"{k}×{v}" for k, v in row.verdicts.items())
            print(f"| {row.scenario_id} | {row.outcome} | {row.correct}/{row.runs} "
                  f"| {verdicts}{mark} |")
    else:
        print("_No records for the full architecture yet._")

    print("\n## Table 5 — Which differences survive chance\n")
    print("Paired by scenario and run. McNemar's exact test on correctness counts only")
    print("the runs where the two arms disagreed; the interval is a paired bootstrap on")
    print("the difference in false-remediation rate, resampling scenarios rather than")
    print("runs (Dror et al., ACL 2018). Rows read A vs B. The verdict uses the Holm-adjusted")
    print("p, which accounts for every test in this table at once (Holm 1979).\n")
    print("| Comparison | A right only / B right only | McNemar p | Holm-adjusted p | FRR(A) − FRR(B), 95% CI | Verdict |")
    print("|---|---:|---:|---:|---|---|")
    deterministic = records_for("pashupatastra")
    runbook = records_for("runbook")
    comparisons: list[dict] = []
    if deterministic and runbook:
        comparisons.append(compare("pashupatastra", deterministic, "runbook", runbook))
    for model in sorted({model for _, model in llm}):
        naive, full = llm.get(("naive-llm", model)), llm.get(("pashupatastra-llm", model))
        if full and naive:
            comparisons.append(compare(f"pashupatastra-llm · {model}", full, f"naive-llm · {model}", naive))
        if naive and runbook:
            comparisons.append(compare(f"naive-llm · {model}", naive, "runbook", runbook))
        if full and deterministic:
            comparisons.append(compare(f"pashupatastra-llm · {model}", full, "pashupatastra", deterministic))
    for row in table5_rows(comparisons):
        print(row)
    if not comparisons:
        print("| — | — | — | — | — | no paired arms recorded yet |")

    print("\n## Table 4 — Metrics not computed\n")
    print("Defined in METRICS.md and absent from the tables above. Listed so a")
    print("reader does not mistake five reported metrics for all of them.\n")
    print("| Metric | Why it is absent |")
    print("|--------|------------------|")
    for metric, reason in NOT_COMPUTABLE.items():
        print(f"| {metric} | {reason} |")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
