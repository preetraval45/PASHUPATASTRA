"""The RP-33 table: every diagnoser on the declared RCAEval sample, from its JSONL records.

    python scripts/rcaevaltable.py > docs/research/models/rcaeval-diagnosis.md

Recomputed from `benchmark/results/rcaeval/*.jsonl`, one line per answer, so a
reader can check every cell. Wilson 95% intervals; errors and abstentions are
counted apart from wrong answers (adr/LLMBaselines).
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

RECORDS = Path(__file__).resolve().parents[1] / "benchmark" / "results" / "rcaeval"
LABEL = {"sati-kaal": "Sati-RCA (trained on Kaal, zero-shot)", "loudest": "Loudest service (no learning)"}


def wilson(k: int, n: int, z: float = 1.96) -> str:
    if not n:
        return "—"
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return f"{p:.3f} [{max(0.0, centre - half):.3f}, {min(1.0, centre + half):.3f}]"


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    rows = []
    for path in sorted(RECORDS.glob("*.jsonl")):
        lines = [json.loads(x) for x in path.read_text(encoding="utf-8").splitlines() if x.strip()]
        if not lines:
            continue
        name = lines[0]["diagnoser"]
        n = len(lines)
        rows.append((LABEL.get(name, name), n, sum(x["hit1"] for x in lines), sum(x["hit3"] for x in lines),
                     sum(x["abstained"] for x in lines), sum(bool(x["error"]) for x in lines)))
    print("<!-- Generated by scripts/rcaevaltable.py from benchmark/results/rcaeval/. Do not edit by hand. -->\n")
    print("# Root cause on real RCAEval cases: Sati against general LLMs (RP-33)\n")
    print("The declared sample (`benchmark/external/rcaeval/subset.json`, `llm_sample`: 50 Online Boutique and 50 "
          "Sock Shop cases, chosen by hash before any run). Every diagnoser sees the same per-service evidence, built by "
          "the RP-32 adapter and never including the label, and is scored by the same harness (RP-14).\n")
    print("| Diagnoser | n | RCA@1 [95% CI] | RCA@3 [95% CI] | Abstained | Errors |")
    print("|---|---:|---:|---:|---:|---:|")
    for label, n, h1, h3, ab, err in rows:
        print(f"| {label} | {n} | {wilson(h1, n)} | {wilson(h3, n)} | {ab} | {err} |")
    if not rows:
        print("| — | 0 | — | — | — | no records yet |")
    print("\nAn error (provider timeout or invalid schema) counts as a miss and is also listed on its own. LLMs run "
          "on CPU through Ollama on GitHub's runners, at temperature 0.2, through the Gateway.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
