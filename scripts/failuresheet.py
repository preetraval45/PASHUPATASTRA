"""RP-34: every wrong RCAEval diagnosis, with a proposed category, for the owner to assign.

    python scripts/failuresheet.py   # writes docs/research/review/rp34-failures.csv and .md

Reads `benchmark/results/rcaeval/*.jsonl`. A failure is any answer that missed
RCA@1, abstained, or errored. Each gets a **proposed** category from a fixed
rule over what the records hold. The `owner_category` column is left empty:
RP-34 is done when the owner has filled it, not when this proposes.

Proposal rules, first match wins:

* **provider error** — the call failed or returned an invalid schema.
* **abstained** — the diagnoser declined.
* **citation dropped** — an answer with no evidence reference behind it.
* **red herring followed** — it named the loudest service, and the loudest
  was not the root (the loudest service is read from the loudest-service
  diagnoser's record for the same case).
* **weak signal at the root** — the root is not among the three loudest
  services, so the evidence barely points at it.
* **right area, wrong service** — the root is in its top 3.
* **unexplained** — none of the above; for the owner to read.

Not proposable from these records, so left to the owner: unseen topology
shape, unseen fault type, right cause but wrong action, policy ceiling.
"""

from __future__ import annotations

import csv
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RECORDS = ROOT / "benchmark" / "results" / "rcaeval"
OUT = ROOT / "docs" / "research" / "review"
ORDER = ("provider error", "abstained", "citation dropped", "red herring followed", "weak signal at the root",
         "right area, wrong service", "unexplained")


def propose(r: dict, loudest: list[str]) -> str:
    if r["error"]:
        return "provider error"
    if r["abstained"]:
        return "abstained"
    if not r["grounded"]:
        return "citation dropped"
    top = r["ranked"][0] if r["ranked"] else None
    if loudest and top == loudest[0] and loudest[0] != r["correct"]:
        return "red herring followed"
    if loudest and r["correct"] not in loudest[:3]:
        return "weak signal at the root"
    if r["correct"] in r["ranked"][:3]:
        return "right area, wrong service"
    return "unexplained"


def fault_of(case: str) -> str:
    """RCAEval names cases `<suite+system>_<service>_<fault>_<repetition>`."""
    parts = case.split("_")
    return parts[-2] if len(parts) >= 4 else "?"


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    by_diagnoser = {}
    for path in sorted(RECORDS.glob("*.jsonl")):
        lines = [json.loads(x) for x in path.read_text(encoding="utf-8").splitlines() if x.strip()]
        if lines:
            by_diagnoser[lines[0]["diagnoser"]] = lines
    loudest = {r["case"]: r["ranked"] for r in by_diagnoser.get("loudest", [])}
    rows = []
    for name, lines in by_diagnoser.items():
        for r in lines:
            if r["hit1"] and not r["abstained"] and not r["error"]:
                continue
            rows.append({"case": r["case"], "fault": fault_of(r["case"]), "diagnoser": name,
                         "answered": " > ".join(r["ranked"][:3]), "correct": r["correct"],
                         "loudest": " > ".join(loudest.get(r["case"], [])[:3]),
                         "proposed": propose(r, loudest.get(r["case"], [])), "owner_category": "", "note": ""})
    OUT.mkdir(parents=True, exist_ok=True)
    with open(OUT / "rp34-failures.csv", "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    names = list(by_diagnoser)
    counts = Counter((r["diagnoser"], r["proposed"]) for r in rows)
    md = [
        "<!-- Generated by scripts/failuresheet.py from benchmark/results/rcaeval/. Do not edit by hand. -->\n",
        "# RP-34 review sheet: wrong RCAEval diagnoses, with proposed categories\n",
        f"{len(rows)} failures (missed RCA@1, abstained or errored) across {len(names)} diagnosers on the declared "
        "100-case sample. Each one is in [rp34-failures.csv](rp34-failures.csv) with a **proposed** category from "
        "a fixed rule (see the script). The `owner_category` column is the owner's to fill; RP-34 is done when "
        "every row has one.\n",
        "## Proposed categories, by diagnoser\n",
        "| Proposed | " + " | ".join(names) + " |",
        "|---|" + "---:|" * len(names),
    ]
    for cat in ORDER:
        if any(counts[(n, cat)] for n in names):
            md.append(f"| {cat} | " + " | ".join(str(counts[(n, cat)]) for n in names) + " |")
    md.append("| **total** | " + " | ".join(str(sum(counts[(n, c)] for c in ORDER)) for n in names) + " |")
    faults = Counter((r["diagnoser"], r["fault"]) for r in rows)
    fault_names = sorted({r["fault"] for r in rows})
    md += ["", "## Failures by injected fault\n", "| Fault | " + " | ".join(names) + " |",
           "|---|" + "---:|" * len(names)]
    md += [f"| {f} | " + " | ".join(str(faults[(n, f)]) for n in names) + " |" for f in fault_names]
    md += ["", "The loudest-service row is red herring by construction: its answer *is* the loudest service. "
           "Packet loss is the fault every diagnoser misses most, Katyayani included.", "",
           "Categories the records cannot propose, which the owner may assign: unseen topology shape, unseen "
           "fault type, right cause but wrong action, policy ceiling."]
    (OUT / "rp34-failures.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{len(rows)} failures written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
