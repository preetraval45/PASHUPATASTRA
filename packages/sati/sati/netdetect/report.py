"""Chandraghanta `results.json` → markdown. Generated, never typed."""

from __future__ import annotations

import json
import sys

READING = {
    "unsw": "Without the TTL fields, the score shows how much of the detection rests on TTL values that "
            "nearly identify the testbed's attack traffic, which a real network would not provide.",
    "cic": "Every test attack family appears only on Thursday or Friday, so the classifier has never seen any of "
           "them. The random-split row is the setting most published results use. The gap between that row "
           "and the by-day result is how much those results owe to the split.",
}


def table(d: dict) -> list[str]:
    rows = ["| Detector | Precision | Recall | F1 | False-positive rate |", "|---|---:|---:|---:|---:|"]
    for name, m in d["detectors"].items():
        label = f"**{name}**" if name.startswith("chandraghanta") else name
        rows.append(f"| {label} | {m['precision']:.3f} | {m['recall']:.3f} | {m['f1']:.3f} | {m['false_positive_rate']:.4f} |")
    ref = d.get("reference_random_split")
    if ref:
        m = ref["chandraghanta-v0"]
        rows.append(f"| *chandraghanta-v0, random split (reference)* | {m['precision']:.3f} | {m['recall']:.3f} | "
                    f"{m['f1']:.3f} | {m['false_positive_rate']:.4f} |")
    return rows


def families(d: dict) -> list[str]:
    names = list(d["detectors"])
    rows = ["| Family | Flows | Seen in training | " + " | ".join(names) + " |",
            "|---|---:|---|" + "---:|" * len(names)]
    for family, f in d["per_family"].items():
        label = family if f["attack"] else f"{family} *(share wrongly flagged)*"
        rows.append(f"| {label} | {f['n']:,} | {'yes' if f['seen_in_training'] else '**no**'} | "
                    + " | ".join(f"{f[n]:.3f}" for n in names) + " |")
    return rows


def main(path: str) -> int:
    with open(path, encoding="utf-8") as handle:
        r = json.load(handle)
    out = [
        "<!-- Generated by packages/sati/sati/netdetect/report.py from the training run. Do not edit by hand. -->\n",
        "# Chandraghanta v0 — network intrusion detection on real labelled flows\n",
        "A LightGBM classifier over each flow's features, with its threshold chosen on a validation slice of the "
        "training data. The baseline is PCA reconstruction error fitted on benign training flows only. "
        "All detectors are scored on the same test flows.\n",
    ]
    for key, d in r["datasets"].items():
        out += [
            f"## {d['name']} — {d['split']}\n",
            f"{d['rows']['train']:,} training flows, {d['rows']['test']:,} test flows, "
            f"{d['attack_share_test']:.1%} of them attacks.\n",
            *table(d),
            "",
            f"{READING[key]}\n",
            "### Recall by attack family\n",
            *families(d),
            "",
        ]
    out += [
        "## How to read this\n",
        f"- Weights are not published: {r['weights_note']}",
        "- Both datasets come from lab testbeds. A model that does well here has learned that testbed's traffic, "
        "not the internet's.",
        "- Designed, written and trained by an AI assistant under the owner's direction "
        "([adr/RealDataModels](../../adr/RealDataModels.md)).",
    ]
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1]))
