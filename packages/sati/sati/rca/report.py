"""Turn a Sati-RCA `results.json` into the markdown table the paper cites.

    python -m sati.rca.report results/sati-rca/results.json > docs/research/models/sati-rca.md

Generated, never typed — the same rule as `scripts/papertables.py`.
"""

from __future__ import annotations

import json
import sys

SCHEMES = {
    "leave-one-system-out": "Leave one system out — a system never seen in training",
    "held-out-fault": "Held-out fault type — a kind of failure never seen in training",
    "held-out-repetition": "Held-out repetition — in-distribution (the optimistic number)",
}


def pct(value: float) -> str:
    return f"{value * 100:.1f}"


def cell(s: dict, k: int) -> str:
    low, high = s[f"ac@{k}_ci"]
    return f"{pct(s[f'ac@{k}'])} ({pct(low)}–{pct(high)})"


def main(path: str) -> int:
    with open(path, encoding="utf-8") as handle:
        r = json.load(handle)
    out = []
    w = out.append
    w("<!-- Generated by packages/sati/sati/rca/report.py from the training workflow. Do not edit by hand. -->\n")
    w("# Sati-RCA v0 — results on real fault-injection data\n")
    d = r["dataset"]
    w(
        f"Trained and tested on **RCAEval** ({d['repo']} @ `{d['revision'][:12]}`), "
        f"{d['cases']} real fault-injection cases on three microservice systems. "
        f"Model `{r['model']}`, sha256 `{r['model_sha256'][:16]}…`. Root cause absent from the "
        f"candidate services in {r['root_not_among_candidates']} case(s) — counted as misses.\n"
    )
    w("AC@k is the share of incidents whose true root-cause service is ranked in the top k; "
      "Avg@5 is the mean of AC@1–AC@5 (RCAEval's headline). Brackets are Wilson 95% intervals. "
      "**Baseline** ranks services by their largest robust shift, with no learning — the "
      "number a model has to beat to be worth being a model.\n")

    w("## Pooled across folds\n")
    w("| Split | Model | AC@1 | AC@3 | AC@5 | Avg@5 | n |")
    w("|---|---|---:|---:|---:|---:|---:|")
    for scheme, title in SCHEMES.items():
        p = r["pooled"].get(scheme)
        if not p:
            continue
        for name, label in (("sati", "**Sati-RCA v0**"), ("baseline", "baseline")):
            s = p[name]
            w(f"| {title.split(' — ')[0]} | {label} | {cell(s, 1)} | {cell(s, 3)} | {cell(s, 5)} | {pct(s['avg@5'])} | {s['n']} |")
    w("")

    w("## Per fold\n")
    w("| Split | Held out | Train cases | Sati AC@1 | Baseline AC@1 | Sati Avg@5 | Baseline Avg@5 | Fault type acc. | n |")
    w("|---|---|---:|---:|---:|---:|---:|---:|---:|")
    for e in r["splits"]:
        fault = e.get("fault_accuracy")
        w(
            f"| {e['scheme']} | `{e['fold']}` | {e['train_cases']} | {cell(e['sati'], 1)} | "
            f"{cell(e['baseline'], 1)} | {pct(e['sati']['avg@5'])} | {pct(e['baseline']['avg@5'])} | "
            f"{'—' if fault is None else pct(fault)} | {e['sati']['n']} |"
        )
    w("")

    if "stress_re3" in r:
        s, b = r["stress_re3"]["sati"], r["stress_re3"]["baseline"]
        w("## Stress test — RE3, code-level faults, never trained on\n")
        w("| Model | AC@1 | AC@3 | AC@5 | Avg@5 | n |")
        w("|---|---:|---:|---:|---:|---:|")
        w(f"| **Sati-RCA v0** | {cell(s, 1)} | {cell(s, 3)} | {cell(s, 5)} | {pct(s['avg@5'])} | {s['n']} |")
        w(f"| baseline | {cell(b, 1)} | {cell(b, 3)} | {cell(b, 5)} | {pct(b['avg@5'])} | {b['n']} |")
        w("")

    ex = r.get("example_explanation")
    if ex:
        w("## What a ranking cites\n")
        w(f"Case `{ex['case']}`, root cause `{ex['service']}` — the features that ranked it, "
          "each traced to the metric series it was computed from:\n")
        w("| Feature | Contribution | Value | Series |")
        w("|---|---:|---:|---|")
        for reason in ex["reasons"]:
            w(f"| `{reason['feature']}` | {reason['contribution']} | {reason['value']} | `{reason['series']}` |")
        w("")

    w("## How to read this\n")
    w("- The leave-one-system-out rows are the claim. The repetition rows are in-distribution "
      "and will look better; the gap between them is how much of the score is memory of a system.")
    w("- Fault-type accuracy is end to end: it is scored on the service Sati-RCA ranked first, "
      "so a wrong root cause is also a wrong fault.")
    w("- These models were designed, written and trained by an AI assistant (Claude) under the "
      "owner's direction ([adr/RealDataModels](../../adr/RealDataModels.md)).")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1]))
