"""How loud the live stack's incidents are, and what that does to the 2σ count (RP-19).

    python -m sati.rca.livesignal --data ../../benchmark/live/dataset --out live-signal.results.json
    python -m sati.rca.livesignal live-signal.results.json      # → markdown

The realism table in `katyayani-live.md` counts a service as anomalous when its
peak shift is at least 2σ. The live stack's load is steady, so its baselines
are nearly flat and their robust scale is tiny. Every service then crosses
2σ in every incident, and the count says nothing about propagation. This
measures that from the committed dataset alone (no training): the peak shift
of the root against the other services, per fault, and how many services
cross 2σ, 10σ and 100σ. A threshold is only meaningful where the root and the
rest separate.
"""

from __future__ import annotations

import argparse
import gzip
import json
import sys
from pathlib import Path

import numpy as np

from sati.rca.live import features

THRESHOLDS = (2, 10, 100)


def measure(data: Path) -> dict:
    meta = json.loads((data / "meta.json").read_text(encoding="utf-8"))
    with gzip.open(data / "incidents.jsonl.gz", "rt", encoding="utf-8") as f:
        records = [json.loads(line) for line in f if line.strip()]
    rows: dict[str, dict[str, list[float]]] = {}
    crossing = {t: [] for t in THRESHOLDS}
    for r in records:
        if "error" in r or not r["samples"]:
            continue
        _, k = features(r, meta["graph"])
        peak = k.set_index("service")["peak"]
        if r["root"] not in peak:
            continue
        for key in (r["fault"], "all"):
            row = rows.setdefault(key, {"root": [], "others": []})
            row["root"].append(float(peak[r["root"]]))
            row["others"].extend(float(x) for x in peak.drop(r["root"]))
        for t in THRESHOLDS:
            crossing[t].append(int((peak >= t).sum()))
    return {
        "incidents": len(crossing[THRESHOLDS[0]]),
        "services": len(meta["services"]),
        "median_peak": {k: {"root": round(float(np.median(v["root"])), 1),
                            "others": round(float(np.median(v["others"])), 1)} for k, v in sorted(rows.items())},
        "mean_services_crossing": {str(t): round(float(np.mean(v)), 2) for t, v in crossing.items()},
    }


def report(r: dict) -> str:
    out = [
        "<!-- Generated by packages/sati/sati/rca/livesignal.py from benchmark/live/dataset. Do not edit by hand. -->\n",
        "# Live stack: how loud the incidents are (RP-19)\n",
        f"{r['incidents']} incidents, {r['services']} services each. Peak shift is the largest robust z of any of a "
        "service's metrics after the fault, against its own pre-fault window.\n",
        "| Fault | Median peak, root (σ) | Median peak, other services (σ) |",
        "|---|---:|---:|",
    ]
    out += [f"| {k} | {v['root']:,.1f} | {v['others']:,.1f} |" for k, v in r["median_peak"].items()]
    out += ["", "| Threshold | Services crossing it, mean per incident |", "|---|---:|"]
    out += [f"| {t}σ | {v:.2f} of {r['services']} |" for t, v in r["mean_services_crossing"].items()]
    out += [
        "",
        "The steady synthetic load leaves near-flat baselines, so even services the fault never reached shift by "
        "tens of σ. At 2σ, the count of anomalous services in the realism table is therefore saturated and is not "
        "evidence about propagation. This is consistent with the Kaal-trained ranker failing here: its "
        "topology features read *which* services are anomalous, and here that is all of them. The rankers that "
        "compare *how much* each service moved (loudest, RCAEval-trained) keep their signal. A consistent account, "
        "not a tested one.",
    ]
    return "\n".join(out)


def main() -> int:
    if len(sys.argv) == 2 and sys.argv[1].endswith(".json"):
        sys.stdout.reconfigure(encoding="utf-8")
        print(report(json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))))
        return 0
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--data", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    args.out.write_text(json.dumps(measure(args.data), indent=1) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
