"""Katyayani on event-level features `results.json` → markdown. Generated, never typed."""

from __future__ import annotations

import json
import sys

NAMES = {"ob": "Online Boutique", "ss": "Sock Shop", "live": "Live stack (RP-19)"}
ROWS = ("events, real-trained", "events, Kaal-trained", "loudest service")


def cell(c: dict) -> str:
    lo, hi = c["ci95"]
    return f"{c['value']:.3f} [{lo:.3f}, {hi:.3f}]"


def main(path: str) -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    with open(path, encoding="utf-8") as handle:
        r = json.load(handle)
    out = [
        "<!-- Generated by packages/sati/sati/rca/eventsreport.py from the training workflow. Do not edit by hand. -->\n",
        "# Katyayani on the features the API can compute\n",
        "The API's incidents hold events (a metric's deviation in σ, its onset, deploys), not raw series, so a "
        "served ranker must read event-level features. Here Katyayani is trained on **real** incidents expressed "
        "in those features and compared, on the same held-out system, with the same features trained on "
        f"{r['kaal_training']['n']:,} synthetic Kaal incidents (what is served today). `deploy_before` is zeroed "
        "everywhere. RCA@1 with 95% intervals.\n",
        "| Held out | Cases | Trained on | Real-trained | Kaal-trained | Loudest service |",
        "|---|---:|---|---:|---:|---:|",
    ]
    for system, row in r["systems"].items():
        trained = ", ".join(NAMES.get(s, s) for s in row["train_systems"])
        out.append(f"| {NAMES.get(system, system)} | {row['cases']} | {trained} | "
                   + " | ".join(cell(row[k]) for k in ROWS) + " |")
    out += ["", f"Features ({len(r['features'])}): {', '.join(r['features'])}. Run time {r['seconds']} s."]
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1]))
