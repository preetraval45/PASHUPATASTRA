"""Kushmanda constrained decoding `results.json` → markdown. Generated, never typed."""

from __future__ import annotations

import json
import sys

ROWS = (
    ("lookup", "exact_match", "Technique ID by name — exact match"),
    ("lookup", "cited_right_passage", "Technique ID by name — cited the right passage"),
    ("classify", "exact_match", "Behaviour → technique — exact match"),
    ("unanswerable", "abstained", "No passage holds the answer — declined"),
)


def main(path: str) -> int:
    with open(path, encoding="utf-8") as handle:
        r = json.load(handle)
    out = [
        "<!-- Generated by packages/sati/sati/lm/constrainedreport.py from the Kaggle run. Do not edit by hand. -->\n",
        "# Kushmanda v2 — constrained decoding for identifiers (RP-44)\n",
        f"{r['questions']} held-out questions whose answer is one identifier: the same seed-7 sample as the training "
        "report. The same model answers each question twice. **Free** decoding is as in "
        "[kushmanda.md](kushmanda.md). In **constrained** decoding the model may only write an identifier present in "
        "its passages, and cites the passage that contains it. If it declines freely, the abstention stands.\n",
        "| Question and measure | Free | Constrained | Word overlap |",
        "|---|---:|---:|---:|",
    ]
    for kind, metric, label in ROWS:
        cells = [r[k].get(kind, {}).get(metric) for k in ("free", "constrained", "lexical baseline")]
        out.append(f"| {label} | " + " | ".join("—" if v is None else f"{v:.3f}" for v in cells) + " |")
    v = r["valid_outputs"]
    out += [
        f"| Valid outputs (an identifier or a declining) | {v['free']:.3f} | {v['constrained']:.3f} | — |",
        "",
        "## How to read this\n",
        "- Constraining guarantees the **form**: every output is an identifier the evidence contains, with a "
        "consistent citation, or a refusal. It cannot make the model **choose** the right one. The remaining "
        "gap to word overlap is in choosing.",
        "- The declining row covers only this ID-question subset, so it differs from the all-questions rate "
        "in [kushmanda.md](kushmanda.md).",
        "- So in serving, the identifier comes from retrieval, and the model writes the explanation around it.",
        f"- Run on `{r['device']}` in {r['seconds']} s; weights are the private Kaggle Model `sati-kushmanda` v2.",
    ]
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1]))
