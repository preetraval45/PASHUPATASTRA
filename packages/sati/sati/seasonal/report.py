"""Render the auto-seasonal NAB results as the generated table in docs/research/models.

    python -m sati.seasonal.report results/auto-seasonal/results.json > docs/research/models/auto-seasonal.md
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def render(results: dict) -> str:
    s = results["summary"]
    data = results["dataset"]
    out = [
        "# Automatic period detection on NAB (generated)",
        "",
        f"Generated by `python -m sati.seasonal.report` from `{data['repo']}` at "
        f"`{data['revision'][:12]}`: {data['series']} real series in {len(data['families'])} families. "
        "Do not edit by hand.",
        "",
        "## Does it ever make a detector blind?",
        "",
        f"- Series where auto-seasonal found a period and switched: **{s['series_with_a_period']}** "
        f"of {data['series']} (periods {', '.join(map(str, s['periods_found'])) or 'none'}).",
        f"- Labelled episodes caught, of {s['episodes']}: "
        + ", ".join(f"{k} {v}" for k, v in s["caught"].items())
        + ".",
        f"- Series where auto-seasonal missed an episode robust-z caught: "
        f"**{len(s['series_where_auto_missed_what_robust_z_caught'])}**"
        + (f" ({', '.join(s['series_where_auto_missed_what_robust_z_caught'])})"
           if s["series_where_auto_missed_what_robust_z_caught"] else "")
        + ".",
        f"- Series where it caught one robust-z missed: "
        f"**{len(s['series_where_auto_caught_what_robust_z_missed'])}**.",
        "",
        "## Mean across families",
        "",
        "| Detector | F1 | Precision | Recall | False alarms / 1000 | Lead |",
        "|---|---|---|---|---|---|",
    ]
    for label, m in results["mean_across_families"].items():
        out.append(
            f"| {label} | {m['f1']:.3f} | {m['precision']:.3f} | {m['recall']:.3f} | "
            f"{m['false_alarms_per_1000']:.1f} | {m['mean_lead']:.1f} |"
        )
    out += ["", "## Series that switched", "", "| Series | Period | Caught (robust-z / auto / @288) |", "|---|---|---|"]
    for r in results["series"]:
        if r["period"] is not None:
            c = r["caught"]
            out.append(
                f"| {r['name']} | {r['period']} | {c['robust-z']} / {c['auto-seasonal']} / "
                f"{c['seasonal-robust-z@288']} of {r['episodes']} |"
            )
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.stdout.write(render(json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))))
