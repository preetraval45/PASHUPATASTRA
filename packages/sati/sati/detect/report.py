"""Shailaputri `results.json` → the markdown table the paper cites. Generated."""

from __future__ import annotations

import json
import sys

LABEL = {
    "shailaputri-v0": "**Shailaputri v0**",
    "robust-z": "robust-z",
    "ewma": "EWMA",
    "seasonal-naive": "seasonal-naive",
    "seasonal-robust-z": "seasonal-robust-z",
}


def main(path: str) -> int:
    with open(path, encoding="utf-8") as handle:
        r = json.load(handle)
    out: list[str] = []
    w = out.append
    w("<!-- Generated by packages/sati/sati/detect/report.py from the training workflow. Do not edit by hand. -->\n")
    w("# Shailaputri v0 — anomaly detection on real metric series\n")
    d = r["dataset"]
    w(f"Trained and tested on **{d['name']}** ({d['repo']} @ `{d['revision'][:12]}`), {d['series']} series in "
      f"{len(d['families'])} families. Each family is held out in turn; the threshold is chosen on the training "
      "families only. Every detector is scored online by the same harness "
      "(`pashupatastra.evaluation.evaluate`) on exactly the same series.\n")
    w("Recall is per anomaly *episode*; false alarms are per 1000 judged points; lead is how many points before "
      "the window's end the first flag came (higher is earlier).\n")

    w("## Mean across held-out families\n")
    w("| Detector | F1 | Precision | Episode recall | False alarms / 1000 | Lead |")
    w("|---|---:|---:|---:|---:|---:|")
    for name, m in r["mean_across_families"].items():
        w(f"| {LABEL.get(name, name)} | {m['f1']:.3f} | {m['precision']:.3f} | {m['recall']:.3f} | "
          f"{m['false_alarms_per_1000']:.1f} | {m['mean_lead']:.1f} |")
    w("")

    w("## Per held-out family\n")
    w("| Held out | Series | Threshold | Detector | F1 | Recall | FA / 1000 |")
    w("|---|---:|---:|---|---:|---:|---:|")
    for f in r["folds"]:
        for name, m in f["detectors"].items():
            w(f"| `{f['held_out']}` | {f['series']} | {f['threshold']} | {LABEL.get(name, name)} | "
              f"{m['f1']:.3f} | {m['recall']:.3f} | {m['false_alarms_per_1000']:.1f} |")
    w("")
    w("## How to read this\n")
    w("- A detector that flags everything catches every episode and drowns the operator; read F1 with false "
      "alarms per 1000, never alone.")
    w("- NAB's labels are windows around each anomaly, and Wu & Keogh (2021) show several NAB series are "
      "trivial or mislabelled — results here inherit those limits.")
    w("- Designed, written and trained by an AI assistant under the owner's direction "
      "([adr/RealDataModels](../../adr/RealDataModels.md)).")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1]))
